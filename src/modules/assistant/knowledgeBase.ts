import { Role } from '../../core/types';

/**
 * Knowledge base for the help assistant (the "RAG" source documents).
 *
 * One entry per thing a user class can do (kind 'feature') or is deliberately
 * NOT allowed to do (kind 'restriction'). It mirrors the "Application
 * Requirements by User Class" matrix in .kiro/steering/steering.md and the
 * FEATURE_MATRIX in core/accessControl.ts — keep all three in sync when a
 * feature is added.
 *
 * `examples` are phrasings a user might type. Each example, the title, and the
 * summary become separate retrieval chunks, so more examples = better recall.
 * `steps` is the instruction path shown to the user.
 */

export type AssistantRole = Role | 'Patient' | 'Visitor';

export const ASSISTANT_ROLES: readonly AssistantRole[] = [
  'Visitor', 'Patient', 'Receptionist', 'Doctor', 'Admin', 'Pharmacy', 'Technician',
];

export interface KbEntry {
  key: string;
  kind: 'feature' | 'restriction';
  roles: AssistantRole[];
  title: string;
  summary: string;
  path: string | null;
  steps: string[];
  examples: string[];
}

const STAFF: AssistantRole[] = ['Receptionist', 'Doctor', 'Admin', 'Pharmacy', 'Technician'];
const MENU = 'Open the ☰ menu at the top of the page';

function f(
  key: string,
  roles: AssistantRole[],
  title: string,
  summary: string,
  path: string | null,
  steps: string[],
  examples: string[]
): KbEntry {
  return { key, kind: 'feature', roles, title, summary, path, steps, examples };
}

function no(key: string, roles: AssistantRole[], title: string, summary: string, examples: string[]): KbEntry {
  return { key, kind: 'restriction', roles, title, summary, path: null, steps: [], examples };
}

